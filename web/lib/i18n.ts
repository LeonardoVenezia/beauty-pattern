const DICTIONARIES: Record<Language, Dict> = { en, es, fr, de, it };

export type TParams = Record<string, string | number>;

function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && value in DICTIONARIES;
}

export function isTKey(key: string): key is TKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

export function translate(lang: Language, key: TKey, params?: TParams): string {
  const text = DICTIONARIES[lang][key] ?? en[key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

const STORAGE_KEY = "tejedora:lang";

/** Guardado > idioma del navegador > ingles. */
function detectLanguage(): Language {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (isLanguage(saved)) return saved;
  } catch {
    // almacenamiento bloqueado: seguimos con el navegador
  }
  const candidates =
    typeof navigator !== "undefined"
      ? [...(navigator.languages ?? []), navigator.language]
      : [];
  for (const candidate of candidates) {
    const code = candidate?.slice(0, 2).toLowerCase();
    if (isLanguage(code)) return code;
  }
  return "en";
}

type I18nContextValue = {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: TKey, params?: TParams) => string;
  /** Traduce si `key` es una clave conocida; si no, devuelve `fallback`. */
  tx: (key: string, fallback?: string, params?: TParams) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  // El HTML estatico sale en ingles; el idioma real se resuelve al montar.
  const [lang, setLangState] = useState<Language>("en");

  useEffect(() => {
    setLangState(detectLanguage());
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Language) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // sin almacenamiento: la eleccion vale solo para esta visita
    }
  }, []);

  const value = useMemo<I18nContextValue>(
    () => ({
      lang,
      setLang,
      t: (key, params) => translate(lang, key, params),
      tx: (key, fallback, params) =>
        isTKey(key) ? translate(lang, key, params) : (fallback ?? key),
    }),
    [lang, setLang],
  );

  return createElement(I18nContext.Provider, { value }, children);
}

export function useT(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useT must be used inside <I18nProvider>.");
  return context;
}
